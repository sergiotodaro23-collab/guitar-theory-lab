#!/usr/bin/env python3
"""
Builds the Studio's hardware pictures: Blender scenes -> renders -> optimised
assets -> manifest and TypeScript geometry for the React components.

    pip install -r tools/blender/requirements.txt       # Blender as a Python module
    python tools/blender/build.py amp                    # everything of the amplifier
    python tools/blender/build.py amp --only body        # one picture
    python tools/blender/build.py amp --samples 24 --preview out/   # quick look, nothing written to src/
    python tools/blender/build.py amp --blend            # also save the scenes in tools/blender/blend/

Also runs inside Blender:  blender -b -P tools/blender/build.py -- amp
Renders are deterministic for a given Blender version (fixed seed, CPU).
"""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
from PIL import Image  # noqa: E402

from components import amp  # noqa: E402
from gtlkit import export  # noqa: E402
from gtlkit.scene import render, save_blend  # noqa: E402

SCALE = 2
ASSETS = os.path.join(ROOT, 'src', 'ui', 'studio', 'v6', 'hardware', 'assets')
GENERATED = os.path.join(ROOT, 'src', 'ui', 'studio', 'v6', 'hardware')
BLEND = os.path.join(HERE, 'blend')
RAW = os.path.join(ROOT, 'test-results', 'blender')


def build_amp(args):
    spec = json.load(open(os.path.join(HERE, 'specs', 'amp.json'), encoding='utf8'))
    out = args.preview or ASSETS
    only = args.only
    made = {}
    timing = {}

    def shot(name, build, *a):
        t = time.time()
        build(*a)
        # One scene per picture; of the knob's frames only the middle one (they differ by one rotation).
        if args.blend and not name[-1].isdigit():
            save_blend(os.path.join(BLEND, f'{name}.blend'))
        path = render(os.path.join(RAW, f'{name}.png'))
        timing[name] = round(time.time() - t, 1)
        return Image.open(path).convert('RGBA')

    if only in (None, 'body'):
        img = export.feather(shot('amp-body', amp.body, spec, args.samples), 4 * SCALE)
        path = os.path.join(out, 'amp-body@2x.webp')
        export.save_webp(img, path, 90)
        fx, fy, fw, fh = amp.frame(spec)
        made['body'] = export.describe(path, fw, fh, SCALE, 'Amplifier head: cabinet, grille, badge, control plate', offset=[fx, fy])
    if only in (None, 'knob'):
        frames = [export.vignette(shot('amp-knob' if i == 15 else f'amp-knob-{i:02d}', amp.knob, spec, max(24, args.samples // 2), a), 0.8, 0.98) for i, a in enumerate(amp.knob_angles(spec))]
        path = os.path.join(out, 'amp-knob-strip@2x.webp')
        export.save_webp(export.strip(frames), path, 88)
        k = spec['knobs']
        made['knob'] = export.describe(path, k['frame'] * k['frames'], k['frame'], SCALE, 'Amplifier knob at every position of its travel (sprite strip)', frames=k['frames'], frame=[k['frame'], k['frame']])
    if only in (None, 'lamp'):
        for lit in (False, True):
            name = 'amp-lamp-on' if lit else 'amp-lamp-off'
            path = os.path.join(out, f'{name}@2x.webp')
            export.save_webp(export.vignette(shot(name, amp.lamp, spec, args.samples, lit), 0.72, 0.98), path, 92)
            f = spec['lamp']['frame']
            made['lampOn' if lit else 'lampOff'] = export.describe(path, f, f, SCALE, 'Pilot lamp, lit' if lit else 'Pilot lamp, off')

    print('seconds per render:', timing)
    if args.preview or only:
        print('preview or partial build: manifest and generated TypeScript not written')
        return
    manifest = {
        'component': spec['id'], 'spec': 'tools/blender/specs/amp.json', 'blender': bpy.app.version_string, 'engine': 'CYCLES', 'samples': args.samples, 'scale': SCALE,
        'assets': made, 'renderSeconds': round(sum(timing.values()), 1),
    }
    export.write_json(os.path.join(ASSETS, 'amp.manifest.json'), manifest)
    header = '// Generated by tools/blender/build.py from tools/blender/specs/amp.json. Do not edit: change the spec and rebuild.'
    export.write_ts(os.path.join(GENERATED, 'amp.generated.ts'), 'AMP_HEAD', {'spec': spec, 'assets': {k: {x: v[x] for x in v if x in ('file', 'px', 'css', 'offset', 'frames', 'frame')} for k, v in made.items()}}, header)


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('component', choices=['amp'])
    ap.add_argument('--only', choices=['body', 'knob', 'lamp'])
    ap.add_argument('--samples', type=int, default=128)
    ap.add_argument('--blend', action='store_true', help='save the scenes next to the scripts')
    ap.add_argument('--preview', metavar='DIR', help='write the pictures here instead of src/')
    args = ap.parse_args(argv)
    {'amp': build_amp}[args.component](args)


if __name__ == '__main__':
    main()
