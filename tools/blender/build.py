#!/usr/bin/env python3
"""
Builds the Studio's hardware pictures: Blender scenes -> renders -> optimised
assets -> manifest and TypeScript geometry for the React components.

    pip install -r tools/blender/requirements.txt       # Blender as a Python module
    python tools/blender/build.py amp                    # everything of the amplifier
    python tools/blender/build.py amp --only body        # one picture
    python tools/blender/build.py amp --samples 24 --preview out/   # quick look, nothing written to src/
    python tools/blender/build.py amp --blend            # also save the scenes in tools/blender/blend/

Also runs inside Blender:  blender -b -P tools/blender/build.py -- amp
Renders are deterministic for a given Blender version (fixed seed, CPU).
"""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
from PIL import Image  # noqa: E402

from components import amp, cab, iface, pedals  # noqa: E402
from gtlkit import export  # noqa: E402
from gtlkit.scene import render, save_blend  # noqa: E402

SCALE = 2
ASSETS = os.path.join(ROOT, 'src', 'ui', 'studio', 'v6', 'hardware', 'assets')
GENERATED = os.path.join(ROOT, 'src', 'ui', 'studio', 'v6', 'hardware')
BLEND = os.path.join(HERE, 'blend')
RAW = os.path.join(ROOT, 'test-results', 'blender')


def build(component, args):
    """
    Renders every picture a component declares. A component module has NAME,
    EXPORT (the name of the generated TypeScript constant) and
    pictures(spec, samples) -> list of dicts:
      key, file, css (w, h), quality, use      what the picture is
      scenes [(name, build)]                   one scene = one picture; several = a sprite strip, left to right
      post(image) -> image                     feathering or vignette
      extra {}                                 more fields for the manifest (offset, frames, frame)
    """
    name = component.NAME
    spec = json.load(open(os.path.join(HERE, 'specs', f'{name}.json'), encoding='utf8'))
    out = args.preview or ASSETS
    made, timing = {}, {}
    for pic in component.pictures(spec, args.samples):
        if args.only and not pic['key'].startswith(args.only):
            continue
        frames = []
        for scene_name, make in pic['scenes']:
            t = time.time()
            make()
            # Of a strip only the scene without a frame number is kept (the frames differ by one rotation).
            if args.blend and not scene_name[-1].isdigit():
                save_blend(os.path.join(BLEND, f'{scene_name}.blend'))
            path = render(os.path.join(RAW, f'{scene_name}.png'))
            timing[scene_name] = round(time.time() - t, 1)
            frames.append(pic['post'](Image.open(path).convert('RGBA')))
        path = os.path.join(out, pic['file'])
        export.save_webp(frames[0] if len(frames) == 1 else export.strip(frames), path, pic['quality'])
        made[pic['key']] = export.describe(path, pic['css'][0], pic['css'][1], SCALE, pic['use'], **pic.get('extra', {}))

    print('seconds per render:', timing)
    print('bytes:', {k: v['bytes'] for k, v in made.items()}, 'total', sum(v['bytes'] for v in made.values()))
    if args.preview or args.only:
        print('preview or partial build: manifest and generated TypeScript not written')
        return
    manifest = {
        'component': spec['id'], 'spec': f'tools/blender/specs/{name}.json', 'blender': bpy.app.version_string, 'engine': 'CYCLES', 'samples': args.samples, 'scale': SCALE,
        'assets': made, 'renderSeconds': round(sum(timing.values()), 1),
    }
    export.write_json(os.path.join(ASSETS, f'{name}.manifest.json'), manifest)
    header = f'// Generated by tools/blender/build.py from tools/blender/specs/{name}.json. Do not edit: change the spec and rebuild.'
    keep = ('file', 'px', 'css', 'offset', 'frames', 'frame')
    export.write_ts(os.path.join(GENERATED, f'{name}.generated.ts'), component.EXPORT, {'spec': spec, 'assets': {k: {x: v[x] for x in v if x in keep} for k, v in made.items()}}, header)


COMPONENTS = {c.NAME: c for c in (amp, cab, iface, pedals)}


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('component', choices=sorted(COMPONENTS))
    ap.add_argument('--only', metavar='KEY', help='only the pictures whose key starts with KEY (body, knob, lamp, ...)')
    ap.add_argument('--samples', type=int, default=128)
    ap.add_argument('--blend', action='store_true', help='save the scenes next to the scripts')
    ap.add_argument('--preview', metavar='DIR', help='write the pictures here instead of src/')
    args = ap.parse_args(argv)
    build(COMPONENTS[args.component], args)


if __name__ == '__main__':
    main()
